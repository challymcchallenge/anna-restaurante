/** Plural românesc: 1 adult, 2 adulți, 20 de adulți. */
export function plural(n: number, one: string, many: string): string {
  if (n === 1) return `1 ${one}`
  const rest = n % 100
  return n >= 20 && (rest === 0 || rest >= 20) ? `${n} de ${many}` : `${n} ${many}`
}

